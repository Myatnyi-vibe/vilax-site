// Типографика при выводе текста из словаря. Словари хранят обычный текст, расстановка — здесь.
import type { Lang } from '../i18n';

const NBSP = String.fromCharCode(0xa0);
// трёхбуквенные предлоги, которые не оставляют в конце строки
const SHORT_PREP = /(^|[\s(«"„])(без|для|над|под|при|про|обо|изо|Без|Для|Над|Под|При|Про) /g;

/**
 * Русский: предлоги, союзы и частицы из 1–2 букв и короткие предлоги (под, для, без…) приклеиваются к следующему слову, «—» к предыдущему,
 * число — к знаку и слову после него («494 ₽», «22 %», «50 сотрудников»).
 * Английский: без изменений (короткие слова в конце строки там допустимы).
 */
export function typo(lang: Lang, text: string): string {
  if (lang !== 'ru') return text;
  return text
    .replace(/(^|[\s(«"„])([а-яёА-ЯЁ]{1,2}) /g, `$1$2${NBSP}`)
    .replace(/(^|[\s(«"„])([а-яёА-ЯЁ]{1,2}) /g, `$1$2${NBSP}`)
    .replace(SHORT_PREP, `$1$2${NBSP}`)
    .replace(/ —/g, `${NBSP}—`)
    .replace(/(\d) (?=[₽%])/g, `$1${NBSP}`)
    .replace(/(\d) (?=[а-яё])/g, `$1${NBSP}`);
}
